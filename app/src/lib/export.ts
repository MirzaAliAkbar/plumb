import type { DocumentAnalysis, Block, PageAnalysis } from './types';
import { joinLines } from './lines';

/**
 * Render the analysis as semantic HTML.
 *
 * This is the durable artifact: the user opens it in their own screen reader, on
 * their own machine, and it announces real headings and real lists. The overlay
 * in the app is evidence; this export is the deliverable.
 */
export function toSemanticHtml(doc: DocumentAnalysis, sourceName: string): string {
  const parts: string[] = [];
  const state = { firstHeadingSeen: false };
  parts.push('<!doctype html>');
  parts.push('<html lang="en">');
  parts.push('<head>');
  parts.push('<meta charset="utf-8">');
  parts.push('<meta name="viewport" content="width=device-width, initial-scale=1">');
  parts.push(`<title>${escapeHtml(sourceName)} — accessible reading copy</title>`);
  parts.push(`<style>${STYLES}</style>`);
  parts.push('</head>');
  parts.push('<body>');
  parts.push('<main>');
  parts.push(`<h1>${escapeHtml(sourceName)}</h1>`);
  parts.push(
    `<p class="meta">Accessible reading copy generated by Plumb. ` +
      `${doc.pageCount} page${doc.pageCount === 1 ? '' : 's'}, ` +
      `reading-order confidence ${Math.round(doc.confidence * 100)}%.</p>`,
  );

  for (const page of doc.pages) {
    parts.push(`<section aria-label="Page ${page.pageIndex + 1}">`);
    parts.push(...renderBlocks(page, state));
    parts.push('</section>');
  }

  parts.push('</main>');
  parts.push('</body>');
  parts.push('</html>');
  return parts.join('\n');
}

function renderBlocks(page: PageAnalysis, state: { firstHeadingSeen: boolean }): string[] {
  const out: string[] = [];
  let listBuffer: Block[] = [];

  const flushList = () => {
    if (listBuffer.length === 0) return;
    out.push('<ul>');
    for (const b of listBuffer) {
      out.push(`<li>${escapeHtml(joinLines(b.lines))}</li>`);
    }
    out.push('</ul>');
    listBuffer = [];
  };

  for (const block of page.blocks) {
    if (block.kind === 'list-item') {
      listBuffer.push(block);
      continue;
    }
    flushList();
    const text = joinLines(block.lines);
    if (!text) continue;
    const low = block.confidence < 0.6 ? ' data-low-confidence="true"' : '';
    switch (block.kind) {
      case 'heading': {
        // Promote the first heading of the document to h2: the document title is
        // h1, so a subheading at h3 would skip a level and break outline
        // navigation — which is how 71.6% of screen-reader users get around.
        const level = state.firstHeadingSeen ? (block.lines[0].size > 18 ? 2 : 3) : 2;
        state.firstHeadingSeen = true;
        out.push(`<h${level}${low}>${escapeHtml(text)}</h${level}>`);
        break;
      }
      case 'caption':
        out.push(`<figure><figcaption${low}>${escapeHtml(text)}</figcaption></figure>`);
        break;
      case 'code':
        out.push(`<pre${low}><code>${escapeHtml(text)}</code></pre>`);
        break;
      default:
        out.push(`<p${low}>${escapeHtml(text)}</p>`);
    }
  }
  flushList();
  return out;
}

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const STYLES = `
:root { color-scheme: light dark; }
body {
  font: 1.125rem/1.7 system-ui, -apple-system, "Segoe UI", sans-serif;
  max-width: 38rem; margin: 0 auto; padding: 2rem 1.25rem;
}
h1 { font-size: 1.6rem; line-height: 1.25; }
h2, h3 { line-height: 1.3; margin-top: 2rem; }
.meta { opacity: .75; font-size: .95rem; }
p { margin: 0 0 1.1em; }
figure { margin: 1.5rem 0; }
figcaption { font-size: .95rem; opacity: .85; border-left: 3px solid currentColor; padding-left: .75rem; }
pre { overflow-x: auto; padding: 1rem; background: rgba(127,127,127,.15); border-radius: .5rem; }
[data-low-confidence="true"] { outline: 2px dashed currentColor; outline-offset: 4px; }
@media (prefers-reduced-motion: no-preference) { html { scroll-behavior: smooth; } }
`;
